// id ของ section ในแต่ละ page ใช้รูปแบบ `sec-<prefix>-<ลำดับ>` (เช่น sec-1-1, sec-3-12, sec-app-a-1)

export interface TocSub {
  /** เลขข้อที่แสดง เช่น "1.1" (ภาคผนวก/หน้าสถาบันจะเป็น null) */
  num: string | null
  title: string
  /** id ของ element ปลายทางในหน้า */
  anchor: string
}

export interface TocGroup {
  /** key เฉพาะของกลุ่ม ใช้จำสถานะกาง/หุบ */
  key: string
  /** ตัวเลข/ตัวอักษรที่โชว์ในวงกลม */
  badge: string
  title: string
  /** route ของหน้า */
  to: string
  /** เป็นภาคผนวกหรือไม่ (ใช้คั่นหัวข้อ "ภาคผนวก" ใน sidebar) */
  appendix?: boolean
  subs: TocSub[]
  /**
   * จำนวนหัวข้อย่อยที่รวมกันเป็น "การ์ดโฟกัส" เดียว เรียงจากหัวข้อแรก
   * เช่น [5, 1, 2, 1, 4] สำหรับหมวด 1 (13 ข้อ) หมายถึง:
   * 1.1-1.5 (5 ข้อ), 1.6 (1 ข้อ), 1.7-1.8 (2 ข้อ), 1.9 (1 ข้อ), 1.10-1.13 (4 ข้อ)
   */
  stepSizes?: number[]
}

/** helper: สร้างรายการหัวข้อย่อยจากอาร์เรย์ชื่อ โดย gen เลขข้อ + anchor ให้อัตโนมัติ */
function subs(prefix: string | number, titles: string[], numbered = true): TocSub[] {
  return titles.map((title, i) => ({
    num: numbered ? `${prefix}.${i + 1}` : null,
    title,
    anchor: `sec-${prefix}-${i + 1}`
  }))
}

